const palavras = (s) => ` ${norm(s).replace(/[^a-z0-9]+/g, ' ').trim()} `;

export function marcasComuns(nomeProduto) {
  const n = palavras(nomeProduto);
  for (const [chaves, marcas] of REGRAS) if (chaves.some((c) => n.includes(palavras(c)))) return marcas;
  return [];
}
